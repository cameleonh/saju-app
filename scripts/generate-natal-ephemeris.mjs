import fs from 'node:fs';
import { createRequire } from 'node:module';

import { EPHEMERIS_FIXTURES } from '../server/domain/annual-ephemeris.mjs';

const require = createRequire(import.meta.url);
const { Solar } = require('lunar-javascript');

const START_YEAR = 1899;
const END_YEAR = 2100;
const TERM_ORDER = [
  ['XIAO_HAN', '小寒'],
  ['LI_CHUN', '立春'],
  ['JING_ZHE', '惊蛰'],
  ['QING_MING', '清明'],
  ['LI_XIA', '立夏'],
  ['MANG_ZHONG', '芒种'],
  ['XIAO_SHU', '小暑'],
  ['LI_QIU', '立秋'],
  ['BAI_LU', '白露'],
  ['HAN_LU', '寒露'],
  ['LI_DONG', '立冬'],
  ['DA_XUE', '大雪'],
];

function sourceSolarToEpochMinute(solar) {
  const [year, month, day, hour, minute, second] = solar.toYmdHms().split(/[- :]/).map(Number);
  return Math.round(Date.UTC(year, month - 1, day, hour - 8, minute, second) / 60_000);
}

const rows = [];
for (let year = START_YEAR; year <= END_YEAR; year += 1) {
  const table = Solar.fromYmdHms(year, 6, 1, 12, 0, 0).getLunar().getJieQiTable();
  const official = EPHEMERIS_FIXTURES[year]?.terms;
  rows.push(TERM_ORDER.map(([key, sourceName]) => {
    if (official?.[key]) return Math.floor(Date.parse(official[key]) / 60_000);
    const solar = table[sourceName] || table[key];
    if (!solar) throw new Error(`missing ${year} ${key}`);
    return sourceSolarToEpochMinute(solar);
  }));
}

const nextYearTable = Solar.fromYmdHms(END_YEAR + 1, 6, 1, 12, 0, 0).getLunar().getJieQiTable();
const nextXiaoHan = nextYearTable['小寒'];
if (!nextXiaoHan) throw new Error(`missing ${END_YEAR + 1} XIAO_HAN sentinel`);
const nextXiaoHanEpochMinute = sourceSolarToEpochMinute(nextXiaoHan);

const body = `// Generated by scripts/generate-natal-ephemeris.mjs. Do not edit by hand.\n`
  + `export const NATAL_EPHEMERIS_START_YEAR = ${START_YEAR};\n`
  + `export const NATAL_EPHEMERIS_END_YEAR = ${END_YEAR};\n`
  + `export const NATAL_EPHEMERIS_NEXT_XIAO_HAN_EPOCH_MINUTE = ${nextXiaoHanEpochMinute};\n`
  + `export const NATAL_TERM_KEYS = Object.freeze(${JSON.stringify(TERM_ORDER.map(([key]) => key))});\n`
  + `export const NATAL_TERM_EPOCH_MINUTES = Object.freeze(${JSON.stringify(rows)}.map((row) => Object.freeze(row)));\n`;

fs.mkdirSync(new URL('../chart/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../chart/natal-ephemeris-data.mjs', import.meta.url), body);
