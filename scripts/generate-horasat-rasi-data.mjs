import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as Astronomy from 'astronomy-engine';

const OUTPUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../chart/horasat-rasi-data.mjs');
const START_YEAR = 1899;
const END_YEAR = 2102;
const MINUTE_MS = 60_000;
const DAY_MS = 86_400_000;
const J2000_JD = 2451545.0;
const J2000_MS = Date.UTC(2000, 0, 1, 12);
const LAHIRI_J2000_DEGREES = 23.853055;
const PRECESSION_ARCSECONDS_PER_YEAR = 50.290966;

function normalizeDegrees(value) {
  return ((value % 360) + 360) % 360;
}

function lahiriSiderealLongitude(epochMs) {
  const jd = epochMs / DAY_MS + 2440587.5;
  const yearsFromJ2000 = (jd - J2000_JD) / 365.2425;
  const ayanamsa = LAHIRI_J2000_DEGREES + yearsFromJ2000 * PRECESSION_ARCSECONDS_PER_YEAR / 3600;
  return normalizeDegrees(Astronomy.SunPosition(new Date(epochMs)).elon - ayanamsa);
}

function signAtMinute(epochMinute) {
  return Math.floor(lahiriSiderealLongitude(epochMinute * MINUTE_MS) / 30);
}

function findIngressMinute(lowMs, highMs, newSign) {
  let low = Math.floor(lowMs / MINUTE_MS);
  let high = Math.ceil(highMs / MINUTE_MS);
  while (high - low > 1) {
    const middle = Math.floor((low + high) / 2);
    if (signAtMinute(middle) === newSign) high = middle;
    else low = middle;
  }
  return high;
}

const startMs = Date.UTC(START_YEAR, 0, 1);
const endMs = Date.UTC(END_YEAR, 0, 1);
const stepMs = 6 * 60 * MINUTE_MS;
const ingressRows = [];
let previousMinute = Math.floor(startMs / MINUTE_MS);
let previousSign = signAtMinute(previousMinute);

for (let probeMs = startMs + stepMs; probeMs <= endMs; probeMs += stepMs) {
  const probeMinute = Math.floor(probeMs / MINUTE_MS);
  let sign = signAtMinute(probeMinute);
  while (sign !== previousSign) {
    const nextSign = (previousSign + 1) % 12;
    const ingressMinute = findIngressMinute(previousMinute * MINUTE_MS, probeMinute * MINUTE_MS, nextSign);
    ingressRows.push([ingressMinute, nextSign]);
    previousSign = nextSign;
    previousMinute = ingressMinute;
    sign = signAtMinute(probeMinute);
  }
  previousMinute = probeMinute;
  previousSign = sign;
}

const lines = [
  '// Generated by scripts/generate-horasat-rasi-data.mjs. Do not edit by hand.',
  `export const HORASAT_RASI_DATA_SOURCE = Object.freeze({ id: 'astronomy-engine-lahiri-solar-ingress', version: 'astronomy-engine-${Astronomy.VERSION || '2.1.19'}-lahiri-v1', timezone: 'UTC instants', precision: 'minute', range: '${START_YEAR}..${END_YEAR - 1}' });`,
  `export const HORASAT_RASI_START_YEAR = ${START_YEAR};`,
  `export const HORASAT_RASI_INGRESSES = Object.freeze(${JSON.stringify(ingressRows)});`,
  '',
];
fs.writeFileSync(OUTPUT, lines.join('\n'));
console.log(`generated ${ingressRows.length} Lahiri sidereal solar ingresses to ${OUTPUT}`);
